static void Servo_SetPulseUs(uint16_t pulse_us)
{
    if (pulse_us < SERVO_MIN_US)
    {
        pulse_us = SERVO_MIN_US;
    }

    if (pulse_us > SERVO_MAX_US)
    {
        pulse_us = SERVO_MAX_US;
    }

    __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_1, pulse_us);
}

static void Servo_SetAngle(uint16_t angle_deg)
{
    uint32_t pulse_us;

    if (angle_deg > 180U)
    {
        angle_deg = 180U;
    }

    pulse_us = SERVO_MIN_US +
               ((uint32_t)angle_deg * (SERVO_MAX_US - SERVO_MIN_US)) / 180U;

    Servo_SetPulseUs((uint16_t)pulse_us);
}

